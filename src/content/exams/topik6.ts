function choices(specs: Spec[], listen: boolean, r: () => number): ExamQuestion[] {
  return specs.flatMap((spec) =>
    sample(spec.bank, spec.n, r).map(([body, options, why]) => ({
      kind: 'choice' as const,
      points: spec.points,
      item: shuffleOptions(
        listen ? { prompt: spec.prompt, ru: spec.ru, audio: body, options, answer: 0, why, errorType: spec.errorType } : { prompt: body, ru: spec.ru, options, answer: 0, why, errorType: spec.errorType },
        r,
      ),
    })),
  );
}


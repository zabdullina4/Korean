import { describe, expect, it } from 'vitest';
import { haeyo, haeyoDistractors } from './conjugate';
import { formatWon, phone, sino, won } from './numbers';

describe('해요체', () => {
  const cases: [string, string][] = [
    ['가다', '가요'], ['오다', '와요'], ['보다', '봐요'], ['먹다', '먹어요'], ['앉다', '앉아요'], ['읽다', '읽어요'],
    ['살다', '살아요'], ['좋다', '좋아요'], ['하다', '해요'], ['공부하다', '공부해요'], ['마시다', '마셔요'],
    ['배우다', '배워요'], ['주다', '줘요'], ['서다', '서요'], ['내다', '내요'], ['켜다', '켜요'], ['되다', '돼요'],
    ['쓰다', '써요'], ['바쁘다', '바빠요'], ['예쁘다', '예뻐요'], ['모르다', '몰라요'], ['부르다', '불러요'],
    ['따르다', '따라요'], ['돕다', '도와요'], ['덥다', '더워요'], ['춥다', '추워요'], ['입다', '입어요'],
    ['듣다', '들어요'], ['걷다', '걸어요'], ['받다', '받아요'], ['낫다', '나아요'], ['웃다', '웃어요'],
    ['그렇다', '그래요'], ['이다', '이에요'], ['아니다', '아니에요'], ['기다리다', '기다려요'], ['쉬다', '쉬어요'],
  ];
  it.each(cases)('%s → %s', (v, f) => expect(haeyo(v)).toBe(f));

  it('варианты-ловушки не совпадают с правильным', () => {
    for (const [v] of cases.filter(([v]) => v !== '이다' && v !== '아니다')) {
      const d = haeyoDistractors(v);
      expect(d.length).toBeGreaterThanOrEqual(2);
      expect(d).not.toContain(haeyo(v));
    }
  });
});

describe('сино-корейские числа', () => {
  const cases: [number, string][] = [
    [1, '일'], [10, '십'], [11, '십일'], [20, '이십'], [100, '백'], [365, '삼백육십오'], [1000, '천'],
    [3500, '삼천오백'], [10000, '만'], [15000, '만 오천'], [24500, '이만 사천오백'], [100000, '십만'],
    [1000000, '백만'], [100000000, '일억'], [123456789, '일억 이천삼백사십오만 육천칠백팔십구'], [0, '영'],
  ];
  it.each(cases)('%i → %s', (n, w) => expect(sino(n)).toBe(w));

  it('цены и телефоны', () => {
    expect(won(3500)).toBe('삼천오백 원');
    expect(formatWon(15000)).toBe('15,000원');
    expect(phone('010-1234-5678')).toBe('공일공에 일이삼사에 오육칠팔');
  });
});
